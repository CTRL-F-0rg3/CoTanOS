use image::GenericImageView;
use std::fs::File;
use std::io::{BufWriter, Write};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args: Vec<String> = std::env::args().collect();
    if args.len() < 3 {
        eprintln!("Użycie: {} <wejscie.png> <wyjscie.rs> [nazwa_zmiennej]", args[0]);
        eprintln!("Przykład: {} logo.png logo.rs LOGO", args[0]);
        std::process::exit(1);
    }

    let input  = &args[1];
    let output = &args[2];
    let var    = args.get(3).map(String::as_str).unwrap_or("IMAGE_DATA");

    let img  = image::open(input)?;
    let (w, h) = img.dimensions();
    let rgba = img.to_rgba8();

    let file = File::create(output)?;
    let mut out = BufWriter::new(file);

    // Nagłówek
    writeln!(out, "// ============================================")?;
    writeln!(out, "// Auto-generated by img2rs")?;
    writeln!(out, "// Source : {}", input)?;
    writeln!(out, "// Size   : {}x{} px", w, h)?;
    writeln!(out, "// Format : 0xRRGGBB (RGB) lub 0xAARRGGBB (z alfą)")?;
    writeln!(out, "// ============================================")?;
    writeln!(out)?;

    let up = var.to_uppercase();
    writeln!(out, "pub const {}_WIDTH : usize = {};",  up, w)?;
    writeln!(out, "pub const {}_HEIGHT: usize = {};",  up, h)?;
    writeln!(out)?;

    // 2D tablica [y][x] – idealna do framebuffera OS-a
    writeln!(out, "pub const {}: [[u32; {}]; {}] = [", var, w, h)?;

    for y in 0..h {
        write!(out, "    [")?;
        for x in 0..w {
            let p = rgba.get_pixel(x, y);
            let (r, g, b, a) = (p[0], p[1], p[2], p[3]);
            if a == 255 {
                write!(out, "0x{:02X}{:02X}{:02X}, ", r, g, b)?;
            } else {
                write!(out, "0x{:02X}{:02X}{:02X}{:02X}, ", a, r, g, b)?;
            }
        }
        writeln!(out, "],")?;
    }
    writeln!(out, "];")?;

    println!("✔ Zapisano: {} ({}x{} px, {} pikseli)", output, w, h, w * h);
    Ok(())
}
