static uint8_t calculate_checksum(const uint8_t *edid) {
    uint8_t sum = 0;
    for (int i = 0; i < 127; i++) sum += edid[i];
    return (uint8_t)(256 - sum);
}

int main(void) {
    edid_t edid;
    
    printf("CoTanOS EDID + VESA Adapter Test\n");
    printf("================================\n\n");
    
    sample_edid[127] = calculate_checksum(sample_edid);
    
    if (edid_parse(sample_edid, 128, &edid) != 0) {
        printf("FAIL: edid_parse failed\n");
        return 1;
    }
    
    printf("--- Before VESA fallback ---\n");
    edid_dump(&edid);
    
    printf("\n--- Adding standard VESA modes (Linux drm_modes adapter) ---\n");
    if (drm_add_standard_modes(&edid) == 0) {
        printf("Successfully added standard VESA modes.\n\n");
        edid_dump(&edid);
    } else {
        printf("FAIL: drm_add_standard_modes failed\n");
    }
    
    edid_free(&edid);
    printf("\n[PASS] All tests successful!\n");
    return 0;
}
