// crates/loomcos-core/src/input.rs
use crate::surface::{Rect, SurfaceId};

pub enum ResizeEdge {
    Top, Bottom, Left, Right,
    TopLeft, TopRight, BottomLeft, BottomRight,
}

pub enum InteractionState {
    Idle,
    Dragging {
        surface_id: SurfaceId,
        grab_offset_x: i32,
        grab_offset_y: i32,
    },
    Resizing {
        surface_id: SurfaceId,
        edge: ResizeEdge,
        initial_bounds: Rect,
        initial_mouse_x: i32,
        initial_mouse_y: i32,
    },
}

pub struct InputManager {
    pub state: InteractionState,
}

impl InputManager {
    pub fn new() -> Self {
        Self {
            state: InteractionState::Idle,
        }
    }

    // Processes mouse button down. Returns dirty rects generated by the action.
    pub fn handle_mouse_down(
        &mut self, 
        x: i32, 
        y: i32, 
        target_id: SurfaceId, 
        bounds: Rect, 
        titlebar_h: i32, 
        border_w: i32
    ) -> Vec<Rect> {
        let mut dirty_rects = Vec::new();
        
        // 1. Check Resize Edges (Priority over titlebar)
        if self.is_on_resize_edge(x, y, bounds, border_w) {
            let edge = self.get_resize_edge(x, y, bounds, border_w);
            dirty_rects.push(bounds); // Mark current area as dirty
            
            self.state = InteractionState::Resizing {
                surface_id: target_id,
                edge,
                initial_bounds: bounds,
                initial_mouse_x: x,
                initial_mouse_y: y,
            };
            return dirty_rects;
        }

        // 2. Check Titlebar (Dragging)
        let local_y = y - bounds.y;
        if local_y >= 0 && local_y < titlebar_h {
            dirty_rects.push(bounds); // Mark current area as dirty
            
            self.state = InteractionState::Dragging {
                surface_id: target_id,
                grab_offset_x: x - bounds.x,
                grab_offset_y: y - bounds.y,
            };
            return dirty_rects;
        }

        // 3. Client Area (Focus only, pass to app later)
        self.state = InteractionState::Idle;
        dirty_rects
    }

    // Processes mouse movement. Returns (new_bounds, dirty_rects).
    pub fn handle_mouse_move(&mut self, x: i32, y: i32, current_bounds: Rect) -> (Rect, Vec<Rect>) {
        let mut dirty_rects = Vec::new();
        let mut new_bounds = current_bounds;

        match &self.state {
            InteractionState::Dragging { surface_id: _, grab_offset_x, grab_offset_y } => {
                // Mark old position as dirty
                dirty_rects.push(current_bounds);
                
                // Calculate new position
                new_bounds.x = x - grab_offset_x;
                new_bounds.y = y - grab_offset_y;
                
                // Mark new position as dirty
                dirty_rects.push(new_bounds);
            }
            InteractionState::Resizing { surface_id: _, edge, initial_bounds, initial_mouse_x, initial_mouse_y } => {
                // Mark old position as dirty
                dirty_rects.push(current_bounds);
                
                let dx = x - initial_mouse_x;
                let dy = y - initial_mouse_y;
                
                // Apply delta based on edge
                match edge {
                    ResizeEdge::Right => new_bounds.width = (initial_bounds.width + dx).max(100),
                    ResizeEdge::Bottom => new_bounds.height = (initial_bounds.height + dy).max(100),
                    ResizeEdge::Left => {
                        let new_w = (initial_bounds.width - dx).max(100);
                        new_bounds.x = initial_bounds.x + (initial_bounds.width - new_w);
                        new_bounds.width = new_w;
                    }
                    ResizeEdge::Top => {
                        let new_h = (initial_bounds.height - dy).max(100);
                        new_bounds.y = initial_bounds.y + (initial_bounds.height - new_h);
                        new_bounds.height = new_h;
                    }
                    _ => {} // Corners can be expanded similarly if needed
                }
                
                // Mark new position as dirty
                dirty_rects.push(new_bounds);
            }
            InteractionState::Idle => {}
        }

        (new_bounds, dirty_rects)
    }

    // Resets state on mouse button release
    pub fn handle_mouse_up(&mut self) {
        self.state = InteractionState::Idle;
    }

    // Helper: Check if coordinates fall within the resize border
    fn is_on_resize_edge(&self, x: i32, y: i32, bounds: Rect, border_w: i32) -> bool {
        let local_x = x - bounds.x;
        let local_y = y - bounds.y;
        
        local_x < border_w || 
        local_x >= bounds.width - border_w || 
        local_y < border_w || 
        local_y >= bounds.height - border_w
    }

    // Helper: Determine which edge/corner is being grabbed
    fn get_resize_edge(&self, x: i32, y: i32, bounds: Rect, border_w: i32) -> ResizeEdge {
        let local_x = x - bounds.x;
        let local_y = y - bounds.y;
        
        let is_left = local_x < border_w;
        let is_right = local_x >= bounds.width - border_w;
        let is_top = local_y < border_w;
        let is_bottom = local_y >= bounds.height - border_w;

        if is_top && is_left { ResizeEdge::TopLeft }
        else if is_top && is_right { ResizeEdge::TopRight }
        else if is_bottom && is_left { ResizeEdge::BottomLeft }
        else if is_bottom && is_right { ResizeEdge::BottomRight }
        else if is_top { ResizeEdge::Top }
        else if is_bottom { ResizeEdge::Bottom }
        else if is_left { ResizeEdge::Left }
        else { ResizeEdge::Right }
    }
}